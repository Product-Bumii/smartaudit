#!/usr/bin/env bash
# One-time (idempotent) provisioning of a host WITHOUT Docker (systemd + nginx), e.g. the test server.
# Run on the server as root, from a directory containing infra/server/*:
#   sudo DOMAIN=efr-staging.bumii.ai bash provision-server.sh
#
# Creates: system user `smartaudit`, /opt/smartaudit/{releases,shared}, a dedicated MongoDB instance
# (port 27018, replica set, auth), systemd units, the nginx site and /opt/smartaudit/shared/.env with
# freshly generated secrets. Never touches other sites, services or MongoDB instances on the host.
set -euo pipefail

DOMAIN="${DOMAIN:-efr-staging.bumii.ai}"
SRC="$(cd "$(dirname "$0")/../server" && pwd)"
APP=/opt/smartaudit
ENV_FILE=$APP/shared/.env
MONGO_MARK=$APP/shared/.mongo-initialized
MONGO_ADMIN_FILE=$APP/shared/mongo-admin.secret

say() { echo "▶ $*"; }
[ "$(id -u)" -eq 0 ] || { echo "run as root (sudo)" >&2; exit 1; }
command -v mongod >/dev/null && command -v mongosh >/dev/null || { echo "mongod and mongosh are required" >&2; exit 1; }
command -v nginx >/dev/null || { echo "nginx is required" >&2; exit 1; }

say "system user and folders"
id smartaudit >/dev/null 2>&1 || useradd --system --home-dir $APP --shell /usr/sbin/nologin smartaudit
mkdir -p $APP/releases $APP/shared
chmod 755 $APP $APP/releases
chown root:smartaudit $APP/shared
chmod 750 $APP/shared

say "dedicated MongoDB instance (port 27018)"
install -d -o mongodb -g mongodb -m 750 /var/lib/mongodb-smartaudit
install -d -o mongodb -g mongodb -m 755 /var/log/mongodb
if [ ! -f /etc/mongod-smartaudit.key ]; then
  openssl rand -base64 756 > /etc/mongod-smartaudit.key
fi
chown mongodb:mongodb /etc/mongod-smartaudit.key
chmod 400 /etc/mongod-smartaudit.key
install -m 644 "$SRC/mongod-smartaudit.conf" /etc/mongod-smartaudit.conf
install -m 644 "$SRC/mongod-smartaudit.service" /etc/systemd/system/mongod-smartaudit.service
systemctl daemon-reload
systemctl enable --now mongod-smartaudit.service
for i in $(seq 1 60); do
  mongosh --port 27018 --quiet --eval 'db.runCommand({ ping: 1 }).ok' >/dev/null 2>&1 && break
  sleep 1
done

if [ ! -f "$MONGO_MARK" ]; then
  say "replica set and users (localhost exception, first run only)"
  mongosh --port 27018 --quiet --eval "try { rs.status().ok } catch (e) { rs.initiate({ _id: 'rs0', members: [{ _id: 0, host: '127.0.0.1:27018' }] }).ok }"
  for i in $(seq 1 60); do
    [ "$(mongosh --port 27018 --quiet --eval 'db.hello().isWritablePrimary')" = "true" ] && break
    sleep 1
  done
  ADMIN_PASS="$(openssl rand -hex 24)"
  APP_PASS="$(openssl rand -hex 24)"
  mongosh --port 27018 --quiet admin --eval "db.createUser({ user: 'saadmin', pwd: '$ADMIN_PASS', roles: ['root'] })" >/dev/null
  mongosh --port 27018 --quiet -u saadmin -p "$ADMIN_PASS" --authenticationDatabase admin --eval \
    "db.getSiblingDB('smartaudit').createUser({ user: 'smartaudit', pwd: '$APP_PASS', roles: [{ role: 'readWrite', db: 'smartaudit' }] })" >/dev/null
  umask 077
  echo "saadmin:$ADMIN_PASS" > "$MONGO_ADMIN_FILE"
  echo "$APP_PASS" > $APP/shared/mongo-app.secret
  umask 022
  touch "$MONGO_MARK"
fi

if [ ! -f "$ENV_FILE" ]; then
  say "environment file with new secrets"
  APP_PASS="$(cat $APP/shared/mongo-app.secret)"
  umask 027
  cat > "$ENV_FILE" <<EOF
# SmartAudit efr · test server (generated by provision-server.sh). Synthetic data only.
NODE_ENV=staging
PORT=3100
MONGO_URL="mongodb://smartaudit:$APP_PASS@127.0.0.1:27018/smartaudit?replicaSet=rs0&authSource=smartaudit"
APP_URL=https://$DOMAIN
CORS_ORIGINS=https://$DOMAIN
TRUST_PROXY=true
JWT_SECRET="$(openssl rand -base64 48 | tr -d '\n')"
FIELD_ENCRYPTION_KEY="$(openssl rand -base64 32 | tr -d '\n')"
EMAIL_HASH_KEY="$(openssl rand -base64 48 | tr -d '\n')"
# No email integration yet: links are dropped and shown on screen (refused in production).
MAIL_PROVIDER=disabled
DEV_SHOW_MAGIC_LINK=true
LOG_LEVEL=info
EOF
  umask 022
  chown root:smartaudit "$ENV_FILE"
  chmod 640 "$ENV_FILE"
fi

say "systemd units"
install -m 644 "$SRC/smartaudit-api.service" /etc/systemd/system/smartaudit-api.service
install -m 644 "$SRC/smartaudit-worker.service" /etc/systemd/system/smartaudit-worker.service
systemctl daemon-reload
systemctl enable smartaudit-api.service smartaudit-worker.service >/dev/null

say "nginx site $DOMAIN"
sed "s/server_name efr-staging.bumii.ai;/server_name $DOMAIN;/" "$SRC/nginx-smartaudit.conf" > /etc/nginx/sites-available/smartaudit
ln -sf /etc/nginx/sites-available/smartaudit /etc/nginx/sites-enabled/smartaudit
nginx -t
systemctl reload nginx

say "provisioning done"
